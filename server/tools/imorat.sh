#!/usr/bin/env bash
# imorat — the one command for the Imorat Go server (installed to /usr/local/bin/imorat by tools/install.sh).
#   imorat status        what is running, API health, disk, last backup
#   imorat logs [api|caddy]   live logs (Ctrl+C to stop)
#   imorat env           edit server/.env in nano, then restart the API
#   imorat restart       restart the API (after editing .env by hand)
#   imorat update        pull the latest code from GitHub, rebuild the API, refresh the site
#   imorat update-site   refresh the website copy and config.js (runs every 10 minutes from cron; rebuilds the API when server code changed)
#   imorat backup        copy the database to /var/backups/imorat (also runs nightly)
#   imorat restore FILE  put a backup back (stops the API for a few seconds)
#   imorat doctor        check DNS, ports, HTTPS, .env and keys — run this when something does not work
#   imorat owner [--login NAME]   set (or change) the owner's login and password for the panel; asks for the password, stores only its hash
set -euo pipefail
REPO_DIR=${IMORAT_REPO_DIR:-/opt/imorat}
SRV=${IMORAT_SRV:-/srv/imorat}
BACKUPS=${IMORAT_BACKUPS:-/var/backups/imorat}
ENV_FILE="$REPO_DIR/server/.env"
QUIET=0; for a in "$@"; do [ "$a" = "--quiet" ] && QUIET=1; done
say() { [ "$QUIET" = 1 ] || echo -e "$*"; }
die() { echo -e "\033[31m$*\033[0m" >&2; exit 1; }
need_root() { [ "$(id -u)" = 0 ] || die "run as root: sudo imorat $*"; }
envget() { grep -E "^$1=" "$ENV_FILE" 2>/dev/null | head -1 | cut -d= -f2- | tr -d '\r' || true; }
dc() { # docker compose with the site override when a site domain is configured
  local files=(-f docker-compose.yml); [ -n "$(envget SITE_DOMAIN)" ] && files+=(-f docker-compose.site.yml)
  (cd "$REPO_DIR/server" && docker compose "${files[@]}" "$@")
}
write_site_config() { # the site reads its settings from config.js; it is generated from .env so the two never disagree
  local api="https://$(envget API_DOMAIN)" ymaps site; ymaps=$(envget YANDEX_MAPS_KEY); site=$(envget SITE_URL)
  [ -n "$site" ] || site="https://$(envget SITE_DOMAIN)/"
  mkdir -p "$SRV/site-config"
  cat > "$SRV/site-config/config.js" <<EOF
/* generated by imorat from server/.env — edit .env, not this file */
window.IMORAT_API = "${api}";
window.IMORAT_SITE = true;
window.IMORAT_SITE_URL = "${site}";
window.IMORAT_YMAPS_KEY = "${ymaps}";
EOF
}
sync_site() { # a copy of the repository without the server, sources and tools is what Caddy serves
  mkdir -p "$SRV/site"
  if command -v rsync >/dev/null 2>&1; then
    rsync -a --delete --exclude .git --exclude server --exclude src --exclude tools --exclude app --exclude '*.py' --exclude '*.md' "$REPO_DIR/" "$SRV/site/"
  else # no rsync: a fresh copy without the private folders
    local tmp; tmp=$(mktemp -d "$SRV/site.XXXX"); (cd "$REPO_DIR" && git archive HEAD | tar -x -C "$tmp"); rm -rf "$tmp/server" "$tmp/src" "$tmp/tools" "$tmp/app"; find "$tmp" -name '*.py' -o -name '*.md' | xargs -r rm -f
    rm -rf "$SRV/site.old"; [ -d "$SRV/site" ] && mv "$SRV/site" "$SRV/site.old"; mv "$tmp" "$SRV/site"; rm -rf "$SRV/site.old"
  fi
  write_site_config
}
git_pull() { (cd "$REPO_DIR" && git fetch -q origin && git reset -q --hard "origin/$(git rev-parse --abbrev-ref HEAD)"); }

cmd=${1:-status}; shift || true
case "$cmd" in
  status)
    echo "— containers"; dc ps
    echo "— API"; curl -fsS --max-time 5 "https://$(envget API_DOMAIN)/api/health" && echo || echo "API is not answering over HTTPS yet (see: imorat doctor)"
    echo "— disk"; df -h / | tail -1
    echo "— database"; dc exec -T api sh -c 'ls -la /data/imorat.db 2>/dev/null; ls /data/backups 2>/dev/null | tail -3' || true
    echo "— host backups"; ls -1t "$BACKUPS" 2>/dev/null | head -3 || echo "none yet"
    echo "— site copy"; (cd "$REPO_DIR" && echo "commit $(git rev-parse --short HEAD) · $(git log -1 --format=%cd --date=short)") ;;
  logs) dc logs -f --tail 200 "${1:-}" ;;
  env) need_root env; ${EDITOR:-nano} "$ENV_FILE"; say "restarting the API with the new settings…"; dc up -d --force-recreate api; write_site_config; say "done — imorat status" ;;
  restart) need_root restart; dc up -d --force-recreate api; say "API restarted" ;;
  update) need_root update; say "pulling the latest code…"; git_pull; say "rebuilding the API…"; dc up -d --build; sync_site; say "updated to $(cd "$REPO_DIR" && git rev-parse --short HEAD)" ;;
  update-site)
    before=$(cd "$REPO_DIR" && git rev-parse HEAD); git_pull || { say "GitHub is not reachable right now — kept the current site"; exit 0; }
    after=$(cd "$REPO_DIR" && git rev-parse HEAD)
    if [ "$before" != "$after" ] || [ ! -f "$SRV/site/index.html" ] || [ "${1:-}" = "--force" ]; then sync_site; say "site refreshed to ${after:0:7}"; else say "site is up to date (${after:0:7})"; fi
    # the site and the API ship together: when the server code changed, rebuild it too (a few seconds of downtime)
    if [ "$before" != "$after" ] && (cd "$REPO_DIR" && git diff --name-only "$before" "$after" | grep -q '^server/'); then say "server code changed — rebuilding the API…"; dc up -d --build >/dev/null 2>&1 && say "API updated"; fi ;;
  backup)
    need_root backup; mkdir -p "$BACKUPS"; f="$BACKUPS/imorat-$(date +%F-%H%M).db"
    # SQLite's own backup API makes a consistent copy even while the API is writing
    dc exec -T api node -e "const{DatabaseSync}=require('node:sqlite');const d=new DatabaseSync('/data/imorat.db');d.exec(\"VACUUM INTO '/data/backup-tmp.db'\");d.close()" \
      && dc cp api:/data/backup-tmp.db "$f" && dc exec -T api rm -f /data/backup-tmp.db
    dc cp api:/data/uploads "$BACKUPS/" 2>/dev/null || true   # product photos live next to the database
    ls -1t "$BACKUPS"/imorat-*.db | tail -n +31 | xargs -r rm -f
    say "backup: $f ($(du -h "$f" | cut -f1))" ;;
  restore)
    need_root restore; [ -f "${1:-}" ] || die "usage: imorat restore /var/backups/imorat/imorat-YYYY-MM-DD-HHMM.db"
    # the file must be a healthy SQLite database before anything is touched
    node -e "const{DatabaseSync}=require('node:sqlite');const d=new DatabaseSync(process.argv[1],{readOnly:true});const r=d.prepare('PRAGMA integrity_check').get();if(r.integrity_check!=='ok')throw new Error(r.integrity_check);console.log('backup is a healthy database:',d.prepare('SELECT count(*) n FROM orders').get().n,'orders')" "$1" 2>/dev/null \
      || dc run --rm --no-deps -T -v "$(cd "$(dirname "$1")" && pwd)/$(basename "$1"):/restore.db:ro" --entrypoint node api -e "const{DatabaseSync}=require('node:sqlite');const d=new DatabaseSync('/restore.db',{readOnly:true});const r=d.prepare('PRAGMA integrity_check').get();if(r.integrity_check!=='ok')throw new Error(r.integrity_check);console.log('backup is a healthy database:',d.prepare('SELECT count(*) n FROM orders').get().n,'orders')" \
      || die "$1 is not a valid Imorat Go database — nothing was changed"
    read -r -p "Replace the live database with $1? Current data after that backup will be lost. [yes/NO] " ok; [ "$ok" = yes ] || exit 1
    dc stop api
    dc cp "$1" api:/data/imorat.db
    # docker cp leaves the file owned by root and a stale write-ahead log would be replayed over the restored data
    dc run --rm --no-deps -T --user root --entrypoint sh api -c 'chown node:node /data/imorat.db && rm -f /data/imorat.db-wal /data/imorat.db-shm'
    dc start api; say "restored; check: imorat status" ;;
  doctor)
    api=$(envget API_DOMAIN); site=$(envget SITE_DOMAIN); ip=$(curl -fsS --max-time 5 https://api.ipify.org || curl -fsS --max-time 5 https://ifconfig.me || echo "?")
    echo "this server's public IP: $ip"
    for d in $api $site ${site:+www.$site}; do
      got=$(getent ahostsv4 "$d" 2>/dev/null | awk '{print $1}' | sort -u | tr '\n' ' ')
      if echo " $got" | grep -q " $ip "; then echo "  DNS $d → $got ✓"; else echo "  DNS $d → ${got:-nothing} ✗  (add an A record pointing to $ip at your registrar; it can take up to an hour)"; fi
    done
    for p in 80 443; do (ss -ltn 2>/dev/null | grep -q ":$p ") && echo "  port $p open ✓" || echo "  port $p not listening ✗ (is Caddy running? imorat logs caddy)"; done
    curl -fsS --max-time 8 "https://$api/api/health" >/dev/null 2>&1 && echo "  https://$api/api/health ✓" || echo "  https://$api/api/health ✗ (certificate not issued yet or the API is down: imorat logs)"
    [ -n "$site" ] && { curl -fsS --max-time 8 -o /dev/null "https://$site/" && echo "  https://$site ✓" || echo "  https://$site ✗"; }
    echo "— .env"
    for k in JWT_SECRET ADMIN_PHONES PUBLIC_URL ALLOWED_ORIGINS; do [ -n "$(envget $k)" ] && echo "  $k set ✓" || echo "  $k EMPTY ✗"; done
    mode=$(envget SMS_MODE); [ -n "$(envget ESKIZ_EMAIL)" ] && mode=eskiz; echo "  sign-in: ${mode:-dev}$([ "${mode:-dev}" = dev ] && echo '  ✗ production will not start — set SMS_MODE=telegram (bot) or ESKIZ_EMAIL/ESKIZ_PASSWORD')"
    for k in TELEGRAM_BOT_TOKEN PAYME_MERCHANT_ID CLICK_SERVICE_ID ANTHROPIC_API_KEY YANDEX_DELIVERY_TOKEN YANDEX_MAPS_KEY; do [ -n "$(envget $k)" ] && echo "  $k ✓" || echo "  $k — not yet (see DEPLOY.md, what it unlocks)"; done
    echo "— containers"; dc ps --format 'table {{.Name}}\t{{.Status}}' 2>/dev/null || dc ps
    echo "— last API log lines"; dc logs --tail 15 api 2>/dev/null | tail -15 ;;
  owner)
    need_root owner; login=""; norestart=0
    while [ $# -gt 0 ]; do case "$1" in --login) login=${2:-}; shift 2 ;; --no-restart) norestart=1; shift ;; *) shift ;; esac; done
    [ -n "$login" ] || login=$(envget OWNER_LOGIN); [ -n "$login" ] || read -r -p "Owner login for the panel (letters, digits, . _ - @): " login
    echo "$login" | grep -qE '^[A-Za-z0-9_.@-]{3,64}$' || die "login: 3–64 letters, digits, . _ - @"
    read -r -s -p "New password (10+ characters, not shown): " p1; echo; read -r -s -p "Once more: " p2; echo
    [ "$p1" = "$p2" ] || die "the two passwords differ — nothing changed"
    [ ${#p1} -ge 10 ] || die "at least 10 characters — nothing changed"
    # the hash is computed inside the API image (node lives there); the password travels over stdin only
    hash=$(printf '%s\n' "$p1" | dc run --rm --no-deps -T --entrypoint node api --disable-warning=ExperimentalWarning tools/owner.mjs hash --stdin 2>/dev/null | tail -1)
    unset p1 p2
    echo "$hash" | grep -q '^scrypt\$' || die "could not compute the hash (is the API image built? imorat update)"
    setenv() { if grep -qE "^#? ?$1=" "$ENV_FILE"; then sed -i -E "s|^#? ?$1=.*|$1=$2|" "$ENV_FILE"; else printf '%s=%s\n' "$1" "$2" >> "$ENV_FILE"; fi; }
    setenv OWNER_LOGIN "$login"; setenv OWNER_PASSWORD_HASH "'$hash'"   # single quotes: Docker Compose must not expand the $ signs inside the hash
    say "owner login: $login — password hash saved to $ENV_FILE"
    if [ "$norestart" = 0 ]; then dc up -d --force-recreate api >/dev/null 2>&1 && say "API restarted; sign in at https://$(envget SITE_DOMAIN)/#owner"; fi ;;
  write-config) write_site_config; say "config.js written" ;;
  *) sed -n '2,12p' "$0"; exit 1 ;;
esac
