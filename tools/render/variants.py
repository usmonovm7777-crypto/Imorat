def build():
    out, renders = [], {}
    for base, items in V.items():
        for k, (ru, uz, pm, km, ov, unit) in enumerate(items, 1):
            img = f"img/p{base}.webp"
            if ov:
                spec = json.loads(json.dumps(SPECS[base]))
                ov = dict(ov)
                lab = ov.pop("L", None)
                spec.update(ov)
                if lab:
                    spec.setdefault("label", {}).update(lab)
                name = f"v{base}_{k}"
                renders[name] = spec
                img = f"img/{name}.webp"
            out.append({"b": base, "ru": ru, "uz": uz, "pm": pm, "km": km, "img": img, **({"u": unit} if unit else {})})
    return out, renders

